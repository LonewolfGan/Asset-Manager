import sharp from "sharp";
import { zipSync } from "fflate";
import { createColorManagedPipeline } from "./image-helpers.js";

export interface FaviconPackOptions {
  name?: string;
  shortName?: string;
  themeColor?: string;
  backgroundColor?: string;
  fit?: "cover" | "contain";
}

/**
 * Builds binary ICO file containing multiple PNG or BMP image frames.
 */
export function buildIcoMulti(images: Array<{ size: number; buf: Buffer }>): Buffer {
  const count = images.length;
  const headerSize = 6;
  const dirSize = 16 * count;
  const totalImgSize = images.reduce((acc, img) => acc + img.buf.length, 0);
  const totalBuf = Buffer.alloc(headerSize + dirSize + totalImgSize);

  // ICONDIR Header
  totalBuf.writeUInt16LE(0, 0); // Reserved (must be 0)
  totalBuf.writeUInt16LE(1, 2); // Type (1 for ICO)
  totalBuf.writeUInt16LE(count, 4); // Number of images

  let dataOffset = headerSize + dirSize;
  for (let i = 0; i < count; i++) {
    const img = images[i];
    const entryOffset = headerSize + i * 16;
    const imgLen = img.buf.length;
    const dim = img.size >= 256 ? 0 : img.size;

    // ICONDIRENTRY
    totalBuf.writeUInt8(dim, entryOffset); // Width
    totalBuf.writeUInt8(dim, entryOffset + 1); // Height
    totalBuf.writeUInt8(0, entryOffset + 2); // Palette colors
    totalBuf.writeUInt8(0, entryOffset + 3); // Reserved
    totalBuf.writeUInt16LE(1, entryOffset + 4); // Color planes
    totalBuf.writeUInt16LE(32, entryOffset + 6); // Bits per pixel
    totalBuf.writeUInt32LE(imgLen, entryOffset + 8); // Image data size in bytes
    totalBuf.writeUInt32LE(dataOffset, entryOffset + 12); // Offset of image data

    img.buf.copy(totalBuf, dataOffset);
    dataOffset += imgLen;
  }

  return totalBuf;
}

/**
 * Generates an HTML snippet ready to embed in <head>.
 */
function buildHtmlSnippet(themeColor: string): string {
  const safeColor = (themeColor ?? "#ffffff").replace(/[^#0-9a-fA-F]/g, "").slice(0, 9) || "#ffffff";
  return `<!-- Favicon & App Icons generated by EverydayTools -->
<link rel="icon" type="image/x-icon" href="/favicon.ico">
<link rel="icon" type="image/png" sizes="16x16" href="/favicon-16x16.png">
<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32x32.png">
<link rel="icon" type="image/png" sizes="48x48" href="/favicon-48x48.png">
<link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png">
<link rel="manifest" href="/site.webmanifest">
<meta name="theme-color" content="${safeColor}">
`;
}

/**
 * Generates standard PWA Web App Manifest JSON.
 */
function buildWebManifest(options: FaviconPackOptions): string {
  const name = options.name ?? "EverydayTools";
  const shortName = options.shortName ?? name;
  const themeColor = options.themeColor ?? "#ffffff";
  const bgColor = options.backgroundColor ?? "#ffffff";

  const manifest = {
    name,
    short_name: shortName,
    icons: [
      {
        src: "/android-chrome-192x192.png",
        sizes: "192x192",
        type: "image/png",
        purpose: "any maskable",
      },
      {
        src: "/android-chrome-512x512.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "any maskable",
      },
    ],
    theme_color: themeColor,
    background_color: bgColor,
    display: "standalone",
  };

  return JSON.stringify(manifest, null, 2);
}

/**
 * Universal Favicon Pack Generator with sRGB calibration, Lanczos3 downscaling,
 * adaptive sharpening, multi-resolution ICO, Apple Touch icon, and PWA manifest.
 */
export async function generateFaviconPack(
  inputBuffer: Buffer,
  options: FaviconPackOptions = {}
): Promise<Buffer> {
  const themeColor = options.themeColor ?? "#ffffff";
  const fitMode = options.fit ?? "cover";

  const sizes = [16, 32, 48, 64, 128, 180, 192, 512];
  const zipEntries: Record<string, Uint8Array> = {};

  // Render each dimension concurrently with color-managed pipeline
  const renderedEntries = await Promise.all(
    sizes.map(async (size) => {
      let pipeline = createColorManagedPipeline(inputBuffer).resize(size, size, {
        fit: fitMode,
        position: "centre",
        kernel: "lanczos3",
      });

      if (size <= 32) {
        pipeline = pipeline.sharpen({ sigma: 0.5, m1: 0.4, m2: 0.4 });
      } else if (size === 48) {
        pipeline = pipeline.sharpen({ sigma: 0.6, m1: 0.3, m2: 0.3 });
      }

      const pngBuffer = await pipeline.png({ compressionLevel: 9, adaptiveFiltering: true }).toBuffer();
      return { size, uint8: new Uint8Array(pngBuffer) };
    })
  );

  for (const { size, uint8 } of renderedEntries) {
    zipEntries[`favicon-${size}x${size}.png`] = uint8;

    if (size === 180) {
      zipEntries["apple-touch-icon.png"] = uint8;
    } else if (size === 192) {
      zipEntries["android-chrome-192x192.png"] = uint8;
    } else if (size === 512) {
      zipEntries["android-chrome-512x512.png"] = uint8;
    }
  }

  // Multi-resolution ICO (16x16, 32x32, 48x48)
  const png16 = Buffer.from(zipEntries["favicon-16x16.png"]);
  const png32 = Buffer.from(zipEntries["favicon-32x32.png"]);
  const png48 = Buffer.from(zipEntries["favicon-48x48.png"]);

  const icoBuffer = buildIcoMulti([
    { size: 16, buf: png16 },
    { size: 32, buf: png32 },
    { size: 48, buf: png48 },
  ]);
  zipEntries["favicon.ico"] = new Uint8Array(icoBuffer);

  // Metadata files
  const manifest = buildWebManifest(options);
  zipEntries["site.webmanifest"] = new TextEncoder().encode(manifest);

  const htmlSnippet = buildHtmlSnippet(themeColor);
  zipEntries["favicon-snippet.html"] = new TextEncoder().encode(htmlSnippet);

  // Package into zip
  const zipped = zipSync(zipEntries, { level: 6 });
  return Buffer.from(zipped);
}
